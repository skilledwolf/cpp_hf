"""Fock matrix construction and energy evaluation (pure functions)."""

from __future__ import annotations

import jax
import jax.numpy as jnp
from jax.scipy.special import xlogy

from .utils import hermitize, selfenergy_fft


def dense_exchange(rho, *, VR, w2d, sectors=None, packing=False):
    """Exchange ``Σ_F[rho] = -IFFT[FFT(w ρ) · VR]`` on the mesh (``VR`` with the shift phase in it).

    ``packing`` transforms only the upper orbital triangle, which needs a
    scalar ``VR`` and a Hermitian ``rho``; ``sectors`` transforms only the
    channels inside each sector.
    """
    return selfenergy_fft(
        VR, w2d[..., None, None] * rho, sectors=sectors, _apply_ifftshift=False,
        hermitian_channel_packing=packing,
    )


def dense_hartree(rho, *, HH, w2d, dtype):
    """k-independent Hartree ``diag(HH n)``, ``n`` the k-summed orbital occupations of ``rho``."""
    n = jnp.sum(w2d[..., None] * jnp.real(jnp.diagonal(rho, axis1=-2, axis2=-1)), axis=(0, 1))
    return jnp.diag((HH @ n).astype(dtype))


def contact(rho, *, w2d, contact_g, contact_Oi, contact_Oj):
    """k-independent ``(σ_H, σ_F)`` of the contact terms, from ``ρ̄ = Σ_k w_k ρ_k``."""
    rho_bar = jnp.einsum("ij,ijab->ab", w2d, rho)
    tr_Oj_rho = jnp.einsum("tij,ji->t", contact_Oj, rho_bar)
    sigma_h = jnp.einsum("t,tij->ij", contact_g * tr_Oj_rho, contact_Oi)
    sigma_f = -jnp.einsum("t,tij,jk,tkl->il", contact_g, contact_Oi, rho_bar, contact_Oj)
    return sigma_h, sigma_f


def build_fock(
    P: jax.Array,
    *,
    h: jax.Array,
    VR: jax.Array,
    refP: jax.Array,
    HH: jax.Array,
    w2d: jax.Array,
    include_exchange: bool,
    include_hartree: bool,
    exchange_hermitian_channel_packing: bool,
    contact_g: jax.Array | None = None,
    contact_Oi: jax.Array | None = None,
    contact_Oj: jax.Array | None = None,
    sectors: tuple[tuple[int, ...], ...] | None = None,
    project_fn=None,
) -> tuple[jax.Array, jax.Array, jax.Array]:
    """``(Σ, H, F)`` with ``F = project(hermitize(h + Σ[P - refP] + H[P - refP]))``.

    ``Σ`` holds the long-range exchange and both contact parts, ``H`` the
    long-range Hartree; the interaction energy is ``½ Tr((Σ + H)(P − refP))``.
    """
    rho = P - refP
    Sigma = (
        dense_exchange(rho, VR=VR, w2d=w2d, sectors=sectors, packing=exchange_hermitian_channel_packing)
        if include_exchange
        else jnp.zeros_like(h)
    )
    H = dense_hartree(rho, HH=HH, w2d=w2d, dtype=h.real.dtype)[None, None] if include_hartree else jnp.zeros_like(h)
    if contact_g is not None:
        sigma_h, sigma_f = contact(rho, w2d=w2d, contact_g=contact_g, contact_Oi=contact_Oi, contact_Oj=contact_Oj)
        Sigma = Sigma + (sigma_h + sigma_f).astype(h.dtype)[None, None]
    F = hermitize(h + Sigma + H)
    if project_fn is not None:
        F = hermitize(jnp.asarray(project_fn(F), dtype=F.dtype))
    return Sigma, H, F


def hf_energy(
    P: jax.Array,
    *,
    h: jax.Array,
    Sigma: jax.Array,
    H: jax.Array,
    weights_b: jax.Array,
    refP: jax.Array | None = None,
) -> jax.Array:
    """Energy whose derivative is the reference-subtracted Fock matrix.

    ``Sigma + H`` is the linear interaction potential generated by
    ``P - refP``.  Its energy is therefore

        E = <h, P> + 0.5 <Sigma + H, P - refP>,

    where the brackets include the k-point quadrature weights.  ``refP``
    defaults to zero for compatibility with callers that do not use
    reference subtraction.
    """
    dP = P if refP is None else P - refP
    return jnp.sum(
        jnp.real(
            jnp.einsum("...ij,...ji->...", weights_b * h, P)
            + 0.5
            * jnp.einsum(
                "...ij,...ji->...", weights_b * (Sigma + H), dP
            )
        )
    )


def occupation_entropy(p: jax.Array, w_norm: jax.Array) -> jax.Array:
    """S = -sum_k w_k sum_i [p*log(p) + (1-p)*log(1-p)]."""
    p_safe = jnp.clip(p, 0.0, 1.0)
    s = xlogy(p_safe, p_safe) + xlogy(1.0 - p_safe, 1.0 - p_safe)
    return -jnp.sum(w_norm[..., None] * s)


def free_energy(
    E: jax.Array,
    p: jax.Array,
    w_norm: jax.Array,
    T: jax.Array,
) -> jax.Array:
    """Free energy Omega = E - T*S(p)."""
    T_val = jnp.maximum(jnp.asarray(T, dtype=p.dtype), jnp.asarray(1e-14, dtype=p.dtype))
    return E - T_val * occupation_entropy(p, w_norm)


def fock_builder(kernel):
    """The Fock builder for ``kernel``: :func:`build_fock`, or the plane-wave one."""
    if kernel.superlattice:
        from .superlattice import superlattice_build_fock

        return superlattice_build_fock(kernel)
    return build_fock
